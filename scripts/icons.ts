/**
 * Generates src/components/ui/icons.tsx: plain-SVG versions of the Lucide icons we use.
 *
 *   pnpm exec tsx scripts/icons.ts
 *
 * Why: in lucide-react 1.x the Icon component is a "use client" module, so every lucide
 * icon (even one rendered by a server component) ships its runtime in the client bundle
 * (~12 KB gzip). These generated components have no hooks or context. They render
 * the same Lucide artwork (ISC licence) and add no client JS when used on the server.
 *
 * To add an icon: put its lucide file name in ICONS below and re-run.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(__dirname, '..');
const LUCIDE = path.join(path.dirname(require.resolve('lucide-react/package.json')), 'dist', 'esm', 'icons');
const OUT = path.join(ROOT, 'src', 'components', 'ui', 'icons.tsx');

/** lucide file name → exported component name. */
const ICONS: Record<string, string> = {
  'arrow-right': 'ArrowRight',
  'arrow-up': 'ArrowUp',
  'chevron-down': 'ChevronDown',
  'chevron-right': 'ChevronRight',
  clock: 'Clock',
  'hand-coins': 'HandCoins',
  mail: 'Mail',
  'map-pin': 'MapPin',
  menu: 'Menu',
  'message-circle': 'MessageCircle',
  milk: 'Milk',
  phone: 'Phone',
  sprout: 'Sprout',
  store: 'Store',
  x: 'X',
};

type Node = [string, Record<string, string | number>][];

const attrs = (a: Record<string, string | number>) =>
  Object.entries(a)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())}=${JSON.stringify(String(v))}`)
    .join(' ');

async function main() {
  const out: string[] = [];
  for (const [file, name] of Object.entries(ICONS)) {
    const mod = (await import(pathToFileURL(path.join(LUCIDE, `${file}.mjs`)).href)) as { __iconData: { node: Node } };
    const children = mod.__iconData.node.map(([tag, a]) => `<${tag} ${attrs(a)} />`).join('');
    out.push(`export const ${name} = (p: IconProps) => <Icon {...p}>${children}</Icon>;`);
  }

  const source = `/* Generated by scripts/icons.ts — do not edit by hand. */
import type { ReactNode, SVGProps } from 'react';

/**
 * Lucide icons as plain SVG components (Lucide artwork, ISC licence). Use these instead
 * of importing lucide-react: its 1.x Icon is a "use client" module that adds ~12 KB of
 * client JS to every page. Decorative by default (aria-hidden); 24×24, stroke 1.75.
 */
export type IconProps = SVGProps<SVGSVGElement> & { strokeWidth?: number };
export type IconComponent = (props: IconProps) => JSX.Element;

function Icon({ children, strokeWidth = 1.75, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

${out.join('\n')}
`;
  fs.writeFileSync(OUT, source);
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${Object.keys(ICONS).length} icons).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

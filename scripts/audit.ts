/**
 * Builds docs/content-audit.md from the crawl output in content/*.json.
 *
 *   pnpm exec tsx scripts/audit.ts
 *
 * Every finding quotes the captured live content; nothing is corrected here.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const CONTENT_DIR = path.join(ROOT, 'content');
const OUT = path.join(ROOT, 'docs', 'content-audit.md');

const crawl = JSON.parse(fs.readFileSync(path.join(CONTENT_DIR, '_crawl.json'), 'utf8'));
const pages: any[] = crawl.pages
  .filter((p: any) => p.captured)
  .map((p: any) => ({ ...p, data: JSON.parse(fs.readFileSync(path.join(CONTENT_DIR, `${p.slug}.json`), 'utf8')) }));
const okPages = pages.filter((p) => p.httpStatus === 200);
const fileOf = (url: string) => new URL(url).pathname.replace(/^\//, '');

const cell = (s: unknown) =>
  String(s ?? '—')
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' / ')
    .trim() || '—';
const quote = (s: string | null | undefined, max = 90) => {
  if (s == null) return '(none)';
  if (s === '') return '(empty)';
  return `“${s.length > max ? s.slice(0, max) + '…' : s}”`;
};
const table = (head: string[], rows: unknown[][]) =>
  rows.length
    ? [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n')
    : '_None found._';
const pagesList = (slugs: Iterable<string>) => {
  const s = [...new Set(slugs)];
  return s.length === okPages.length && s.length > 3 ? `all ${s.length} pages` : s.join(', ');
};
const sectionName = (s: any) => (s.kind === 'content' ? `§${s.index} ${s.headings[0]?.text ?? s.className ?? ''}`.trim() : s.kind);

// Every anchor on every page, with context.
interface LinkUse {
  page: string;
  section: string;
  sectionKind: string;
  label: string;
  href: string | null;
  url: string | null;
  kind: string;
  context?: string;
}
const linkUses: LinkUse[] = [];
for (const p of pages) {
  for (const s of p.data.sections) {
    const cardOf = new Map<string, string>();
    for (const c of s.cards) for (const l of c.links) cardOf.set(`${l.label}|${l.href}`, c.headings[0]?.text ?? '');
    for (const l of s.links) {
      linkUses.push({
        page: p.slug,
        section: sectionName(s),
        sectionKind: s.kind,
        label: l.label || (l.icons.length ? `[icon: ${l.icons.join(' ')}]` : ''),
        href: l.href,
        url: l.url,
        kind: l.kind,
        context: cardOf.get(`${l.label}|${l.href}`),
      });
    }
  }
}
const groupBy = <T,>(xs: T[], key: (x: T) => string) => {
  const m = new Map<string, T[]>();
  for (const x of xs) m.set(key(x), [...(m.get(key(x)) ?? []), x]);
  return m;
};

const md: string[] = [];
const push = (...lines: string[]) => md.push(...lines, '');

push(
  '# Content audit — shreeshyamfoundation.in',
  `Generated by \`scripts/audit.ts\` from the crawl of ${crawl.origin} on ${crawl.crawledAt.slice(0, 10)}. ` +
    'All quoted text is verbatim from the live site. Re-run `pnpm exec tsx scripts/crawl.ts && pnpm exec tsx scripts/audit.ts` to refresh.',
);

// ---------------------------------------------------------------------------
push('## 1. Pages crawled');
push(
  table(
    ['Page', 'HTTP', 'Source', 'Linked from', 'Sections', 'Forms'],
    crawl.pages.map((p: any) => {
      const d = pages.find((x) => x.slug === p.slug)?.data;
      return [
        fileOf(p.url),
        p.httpStatus ?? 'error',
        p.seed ? 'seed list' : 'discovered',
        p.linkedFrom.filter((x: string) => x !== 'seed').length ? pagesList(p.linkedFrom.filter((x: string) => x !== 'seed')) : '—',
        d ? d.sections.filter((s: any) => s.kind !== 'scroll-to-top' && s.kind !== 'preloader').length : '—',
        d ? d.forms.length : '—',
      ];
    }),
  ),
);

// ---------------------------------------------------------------------------
push('## 2. Broken links');
const broken = Object.entries(crawl.linkStatus as Record<string, any>).filter(([, r]) => r.status == null || r.status >= 400);
// Social networks answer automated requests with 400/403/999, and timeouts prove nothing either way.
const botBlocked = (url: string, status: number | null) =>
  status === 999 || (status != null && status >= 400 && status < 500 && /linkedin|instagram|facebook|twitter|x\.com/.test(url));
const unverified = (r: any) => r.status == null && /timeout/i.test(r.error ?? '');
const realBroken = broken.filter(([u, r]) => !botBlocked(u, r.status) && !unverified(r));
push('Links and assets whose URL returned an HTTP error (or no response) during the crawl.');
push(
  table(
    ['URL', 'Result', 'Used on', 'Link labels'],
    realBroken.map(([u, r]) => {
      const uses = linkUses.filter((l) => l.url === u);
      const assetUses = pages.filter((p) => p.data.assets.some((a: any) => a.url === u)).map((p) => p.slug);
      return [
        u,
        r.status ?? r.error ?? 'no response',
        pagesList([...uses.map((l) => l.page), ...assetUses]) || '—',
        [...new Set(uses.map((l) => l.label))].map((l) => quote(l, 40)).join(', ') || (assetUses.length ? '(image/asset)' : '—'),
      ];
    }),
  ),
);
const blocked = broken.filter(([u, r]) => botBlocked(u, r.status));
if (blocked.length) push(`Not counted as broken (the social network refuses automated requests; see §3 — these are bare home pages anyway): ${blocked.map(([u, r]) => `${u} (${r.status})`).join(', ')}.`);
const timedOut = broken.filter(([, r]) => unverified(r));
if (timedOut.length) push(`Not verified (request timed out; check by hand): ${timedOut.map(([u]) => u).join(', ')}.`);

// ---------------------------------------------------------------------------
push('## 3. Placeholder and social links');
const SOCIAL = /(^|\.)(facebook|twitter|x|instagram|linkedin|youtube|pinterest|whatsapp)\.com$/;
const isSocialRoot = (u: string | null) => {
  if (!u) return false;
  try {
    const x = new URL(u);
    return SOCIAL.test(x.hostname.replace(/^www\./, '')) && (x.pathname === '/' || x.pathname === '') && !x.search;
  } catch {
    return false;
  }
};
const placeholderHref = (l: LinkUse) =>
  l.kind === 'javascript' ? 'javascript: (does nothing)' :
  l.kind === 'empty-anchor' ? `"${l.href}" (goes nowhere)` :
  l.kind === 'no-href' ? 'no href' :
  /x{4,}/i.test(l.href ?? '') ? 'placeholder number/address' :
  isSocialRoot(l.url) ? 'social network home page, not a profile' : null;
const placeholders = linkUses.map((l) => ({ ...l, why: placeholderHref(l) })).filter((l) => l.why);
push(
  table(
    ['href', 'Why', 'Labels / context', 'Where', 'Count'],
    [...groupBy(placeholders, (l) => `${l.href}|${l.why}`).values()].map((g) => [
      `\`${g[0].href ?? '(none)'}\``,
      g[0].why,
      [...new Set(g.map((l) => (l.context ? `${quote(l.label, 30)} in card ${quote(l.context, 40)}` : quote(l.label, 40))))].slice(0, 8).join(', ') +
        (new Set(g.map((l) => l.label + l.context)).size > 8 ? ' …' : ''),
      [...new Set(g.map((l) => l.section))].join(', ') + ` — ${pagesList(g.map((l) => l.page))}`,
      g.length,
    ]),
  ),
);
const textPlaceholders: string[][] = [];
const PLACEHOLDER_TEXT = /(lorem ipsum|x{4,}|\bplaceholder\b|\bexample\.com\b|your (name|email|company)|\btbd\b|coming soon|dummy)/i;
for (const p of pages)
  for (const s of p.data.sections)
    for (const b of s.blocks) if (b.text && PLACEHOLDER_TEXT.test(b.text)) textPlaceholders.push([p.slug, sectionName(s), quote(b.text, 120)]);
push('**Placeholder text in visible content**');
push(table(['Page', 'Section', 'Text'], textPlaceholders));
const commented = new Map<string, Set<string>>();
for (const p of pages)
  for (const c of p.data.htmlComments)
    if (PLACEHOLDER_TEXT.test(c) || /javascript:void|href="#"/.test(c)) {
      const snippet = (c.match(/.{0,60}(x{4,}|lorem ipsum|javascript:void\(0\)|href="#").{0,40}/i)?.[0] ?? c.slice(0, 100)).replace(/\s+/g, ' ');
      commented.set(snippet, (commented.get(snippet) ?? new Set()).add(p.slug));
    }
push('**Placeholders inside commented-out HTML** (not visible today, but would reappear if the markup is un-commented)');
push(table(['Snippet', 'Pages'], [...commented].map(([s, ps]) => [`\`${s}\``, pagesList(ps)])));

// ---------------------------------------------------------------------------
push('## 4. Empty and missing values');
const empties: string[][] = [];
const titleless = okPages.filter((p) => !p.data.meta.title);
if (titleless.length) empties.push(['`<title>`', 'missing', pagesList(titleless.map((p) => p.slug))]);
for (const key of ['description', 'canonical', 'robots'] as const) {
  const miss = okPages.filter((p) => !p.data.meta[key]);
  if (miss.length) empties.push([`meta ${key}`, 'missing', pagesList(miss.map((p) => p.slug))]);
}
const noOg = okPages.filter((p) => !Object.keys(p.data.meta.og).length);
if (noOg.length) empties.push(['Open Graph tags (og:*)', 'none present', pagesList(noOg.map((p) => p.slug))]);
const noTw = okPages.filter((p) => !Object.keys(p.data.meta.twitter).length);
if (noTw.length) empties.push(['Twitter card tags', 'none present', pagesList(noTw.map((p) => p.slug))]);
for (const p of pages.filter((x) => x.httpStatus !== 200))
  empties.push([fileOf(p.url), `whole page empty (HTTP ${p.httpStatus}); no content could be captured`, p.slug]);
const noH1 = okPages.filter((p) => !p.data.sections.some((s: any) => s.headings.some((h: any) => h.level === 1)));
if (noH1.length) empties.push(['`<h1>`', 'missing', pagesList(noH1.map((p) => p.slug))]);
const multiH1 = okPages.filter((p) => p.data.sections.flatMap((s: any) => s.headings).filter((h: any) => h.level === 1).length > 1);
for (const p of multiH1)
  empties.push(['`<h1>`', `${p.data.sections.flatMap((s: any) => s.headings).filter((h: any) => h.level === 1).length} on one page`, p.slug]);
const perPage = (pred: (s: any, p: any) => string[]) =>
  okPages.flatMap((p) => p.data.sections.flatMap((s: any) => pred(s, p).map((what) => [what, sectionName(s), p.slug])));
const emptyRows = perPage((s) => [
  ...s.headings.filter((h: any) => !h.text).map((h: any) => `empty <h${h.level}>`),
  ...s.blocks.filter((b: any) => b.type === 'paragraph' && !b.text).map(() => 'empty <p>'),
  ...s.ctas.filter((c: any) => !c.label).map((c: any) => `button/CTA with no label (${c.href ?? c.element})`),
  ...s.team.flatMap((m: any) => [
    ...(!m.name ? ['team member without a name'] : []),
    ...(!m.role ? [`team member ${quote(m.name)} has no role`] : []),
    ...(!m.photo ? [`team member ${quote(m.name)} has no photo`] : []),
  ]),
  ...s.testimonials.flatMap((t: any) => [...(!t.name ? ['testimonial without a name'] : []), ...(!t.photo ? [`testimonial by ${quote(t.name)} has no photo`] : []), ...(!t.role ? [`testimonial by ${quote(t.name)} has no role/location`] : [])]),
  ...s.stats.filter((x: any) => !x.label).map((x: any) => `stat ${x.value} has no label`),
  ...s.faqs.filter((f: any) => !f.answer).map((f: any) => `FAQ ${quote(f.question)} has no answer`),
]);
// Collapse identical rows (e.g. the same testimonial gap repeated) per page.
const emptyGroups = groupBy(emptyRows, (r) => `${r[0]}|${r[1]}`);
for (const g of emptyGroups.values()) empties.push([g[0][0], g[0][1], pagesList(g.map((r) => r[2]))]);
const iconOnly = linkUses.filter((l) => l.label.startsWith('[icon:') || l.label === '');
for (const g of groupBy(iconOnly, (l) => `${l.href}`).values())
  empties.push([`link to \`${g[0].href}\` has no text or aria-label`, `${g[0].label || 'no content'}`, pagesList(g.map((l) => l.page))]);
for (const p of okPages)
  for (const f of p.data.forms)
    for (const field of f.fields) {
      const problems = [
        ...(!field.label ? ['no <label> text'] : []),
        ...(!field.name && field.type !== 'hidden' ? ['no name attribute (value is never submitted)'] : []),
      ];
      if (problems.length)
        empties.push([`form field ${field.name ?? field.id ?? field.placeholder ?? field.type}`, problems.join('; ') + (field.placeholder ? ` — placeholder ${quote(field.placeholder)}` : ''), `${p.slug} (form → ${f.action})`]);
    }
push(table(['Item', 'Problem', 'Where'], empties));

push('**Embedded iframes** (compare the map’s pinned place with the published address)');
push(
  table(
    ['Page', 'Embed', 'Pinned place (from the URL)', 'title attribute'],
    okPages.flatMap((p) =>
      p.data.sections.flatMap((s: any) =>
        s.iframes.map((f: any) => [
          p.slug,
          f.src ? new URL(f.src).hostname + new URL(f.src).pathname : '(no src)',
          decodeURIComponent(f.src?.match(/!2s([^!]+)/)?.[1] ?? '—'),
          f.title ?? 'missing',
        ]),
      ),
    ),
  ),
);

// ---------------------------------------------------------------------------
push('## 5. Missing alt text');
push('`missing` means the `alt` attribute is not there at all; `empty` means `alt=""` (marks the image as decorative, which is wrong for content photos, logos and icons that carry meaning).');
const altRows = new Map<string, { alt: string; pages: Set<string>; sections: Set<string> }>();
for (const p of okPages)
  for (const s of p.data.sections)
    for (const i of s.images)
      if (i.kind === 'img' && (i.altMissing || !i.alt?.trim())) {
        const k = i.src ?? i.url;
        const r = altRows.get(k) ?? { alt: i.altMissing ? 'missing' : 'empty', pages: new Set(), sections: new Set() };
        r.pages.add(p.slug);
        r.sections.add(s.kind === 'content' ? (s.headings[0]?.text ?? s.className ?? 'content') : s.kind);
        altRows.set(k, r);
      }
const imgTotal = okPages.flatMap((p) => p.data.sections.flatMap((s: any) => s.images.filter((i: any) => i.kind === 'img'))).length;
push(`${altRows.size} distinct images (of ${imgTotal} \`<img>\` uses) lack alt text. Background images (CSS) can't have alt text and are listed in each page's JSON instead.`);
push(table(['Image', 'alt', 'Section', 'Pages'], [...altRows].map(([src, r]) => [`\`${src}\``, r.alt, [...r.sections].join(', '), pagesList(r.pages)])));

// ---------------------------------------------------------------------------
push('## 6. Duplicate content');
const dupMeta = (key: string, get: (p: any) => string | null) => {
  const g = groupBy(okPages.filter((p) => get(p)), (p) => get(p)!);
  return [...g].filter(([, ps]) => ps.length > 1).map(([v, ps]) => [key, quote(v, 100), pagesList(ps.map((p) => p.slug))]);
};
push('**Shared page titles / descriptions**');
push(table(['Field', 'Value', 'Pages'], [...dupMeta('<title>', (p) => p.data.meta.title), ...dupMeta('meta description', (p) => p.data.meta.description)]));

const BODY_KINDS = new Set(['content', 'hero']);
const textUses = new Map<string, { text: string; uses: { page: string; section: string }[] }>();
for (const p of okPages)
  for (const s of p.data.sections) {
    if (!BODY_KINDS.has(s.kind)) continue;
    for (const b of s.blocks) {
      if (!b.text || b.text.length < 60) continue;
      const key = b.text.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
      const e = textUses.get(key) ?? { text: b.text as string, uses: [] as { page: string; section: string }[] };
      e.uses.push({ page: p.slug, section: sectionName(s) });
      textUses.set(key, e);
    }
  }
const dups = [...textUses.values()].filter((e) => e.uses.length > 1).sort((a, b) => b.uses.length - a.uses.length);
push('**Paragraphs repeated across or within pages** (body content only; the shared header/footer is excluded; ≥60 characters)');
push(
  table(
    ['Text', 'Times', 'Where'],
    dups.map((e) => [quote(e.text, 110), e.uses.length, [...groupBy(e.uses, (u) => u.page)].map(([pg, us]) => `${pg}${us.length > 1 ? ` ×${us.length}` : ''}`).join(', ')]),
  ),
);
const sectionSig = new Map<string, string[]>();
for (const p of okPages)
  for (const s of p.data.sections) {
    if (!BODY_KINDS.has(s.kind) || !s.headings.length) continue;
    const sig = JSON.stringify(s.blocks.map((b: any) => b.text ?? b.items?.map((i: any) => i.text)));
    if (sig.length < 200) continue;
    sectionSig.set(sig, [...(sectionSig.get(sig) ?? []), `${p.slug} (${s.headings[0].text})`]);
  }
push('**Whole sections repeated on several pages**');
push(table(['Section', 'Pages'], [...sectionSig.values()].filter((v) => v.length > 1).map((v) => [v[0].replace(/^.*?\(/, '').replace(/\)$/, ''), v.map((x) => x.split(' (')[0]).join(', ')])));
const sameImg = new Map<string, Set<string>>();
for (const p of okPages)
  for (const a of p.data.assets) if (a.bytes) sameImg.set(`${a.bytes}|${a.contentType}`, (sameImg.get(`${a.bytes}|${a.contentType}`) ?? new Set()).add(a.url));
const renamedCopies = [...sameImg.values()].filter((s) => s.size > 1);
push('**Same image file published under different URLs** (identical size and type)');
push(table(['URLs'], renamedCopies.map((s) => [[...s].map((u) => `\`${fileOf(u)}\``).join(' = ')])));

// ---------------------------------------------------------------------------
push('## 7. Links pointing to the wrong page');
push(
  'A link is flagged when its label names a page (it matches that page’s label in the site navigation, or a word unique to that page’s URL, such as “livestock” or “career”) but its `href` goes somewhere else. For card links the card heading is checked too.',
);
// Label → URL according to the header/footer navigation of the home page.
const navMap = new Map<string, string>();
const home = okPages.find((p) => p.slug === 'index') ?? okPages[0];
for (const s of home.data.sections.filter((x: any) => x.kind === 'header' || x.kind === 'footer'))
  for (const l of s.links) if (l.kind === 'internal' && l.label) navMap.set(l.label.toLowerCase().trim(), l.url);
const pageKeys: { url: string; slug: string; tokens: string[] }[] = pages.map((p) => ({ url: p.url, slug: p.slug, tokens: p.slug.split(/[-_]+/) }));
const tokenCount = new Map<string, number>();
for (const k of pageKeys) for (const t of new Set(k.tokens)) tokenCount.set(t, (tokenCount.get(t) ?? 0) + 1);
const distinct = (t: string) => t.length >= 4 && tokenCount.get(t) === 1;
const stem = (w: string) => w.toLowerCase().replace(/[^a-z]/g, '').slice(0, 5);
const pagesNamedBy = (label: string) => {
  const words = new Set(label.split(/\s+/).map(stem).filter((w) => w.length >= 4));
  return pageKeys.filter((k) => k.tokens.some((t) => distinct(t) && words.has(stem(t))));
};
const wrong: string[][] = [];
const seenWrong = new Set<string>();
for (const l of linkUses) {
  if (l.kind !== 'internal' || !l.url) continue;
  const label = l.label.toLowerCase().trim();
  const reasons: string[] = [];
  const navTarget = navMap.get(label);
  if (navTarget && navTarget !== l.url) reasons.push(`the navigation uses ${quote(l.label)} for \`${fileOf(navTarget)}\``);
  else if (!navTarget) {
    const named = pagesNamedBy(l.label);
    if (named.length && !named.some((k) => k.url === l.url)) reasons.push(`the label names \`${named.map((k) => fileOf(k.url)).join('`/`')}\``);
    if (l.context) {
      const cardNamed = pagesNamedBy(l.context);
      if (cardNamed.length && !cardNamed.some((k) => k.url === l.url)) reasons.push(`card ${quote(l.context, 50)} is about \`${cardNamed.map((k) => fileOf(k.url)).join('`/`')}\``);
    }
  }
  if (!reasons.length) continue;
  const key = `${l.page}|${l.label}|${l.url}`;
  if (seenWrong.has(key)) continue;
  seenWrong.add(key);
  wrong.push([quote(l.label), `\`${l.href}\``, reasons.join('; '), `${l.page} — ${l.section}`]);
}
push(table(['Label', 'href', 'Why it looks wrong', 'Where'], wrong));
push('**How each page is named** (navigation label vs. `<title>` vs. `<h1>`; differences can mean a link or title points at the wrong thing)');
push(
  table(
    ['Page', 'Navigation / footer labels', '<title>', '<h1>'],
    pages.map((p) => [
      fileOf(p.url),
      [...new Set(linkUses.filter((l) => l.url === p.url && (l.sectionKind === 'header' || l.sectionKind === 'footer') && l.label && !l.label.startsWith('[icon')).map((l) => quote(l.label)))].join(', ') || '—',
      quote(p.data.meta.title),
      p.data.sections.flatMap((s: any) => s.headings.filter((h: any) => h.level === 1).map((h: any) => quote(h.text, 60))).join(' + ') || '(none)',
    ]),
  ),
);
const toBroken = linkUses.filter((l) => l.kind === 'internal' && l.url && pages.some((p) => p.url === l.url && p.httpStatus !== 200));
push('**Navigation entries that lead to error pages**');
push(
  table(
    ['Label', 'Target', 'Target status', 'Where'],
    [...groupBy(toBroken, (l) => `${l.label}|${l.url}`).values()].map((g) => [
      quote(g[0].label),
      `\`${g[0].href}\``,
      pages.find((p) => p.url === g[0].url)?.httpStatus,
      `${[...new Set(g.map((l) => l.section))].join(', ')} — ${pagesList(g.map((l) => l.page))}`,
    ]),
  ),
);

// ---------------------------------------------------------------------------
push('## 8. Forms (for reference)');
for (const p of okPages)
  for (const f of p.data.forms) {
    push(
      `**${p.slug}** — \`${f.method.toUpperCase()} ${f.action}\`${f.enctype ? ` (${f.enctype})` : ''}`,
      table(
        ['Label', 'name', 'type', 'required', 'options / notes'],
        f.fields.map((x: any) => [
          x.label ?? `(no label${x.placeholder ? `; placeholder ${quote(x.placeholder)}` : ''})`,
          x.name ?? '(none)',
          x.type,
          x.required ? 'yes' : 'no',
          [x.options?.map((o: any) => o.label).join(', '), x.maxlength && `maxlength ${x.maxlength}`, x.accept && `accept ${x.accept}`].filter(Boolean).join('; '),
        ]),
      ),
    );
  }

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md.join('\n').replace(/\n{3,}/g, '\n\n'));
console.log(`Wrote ${path.relative(ROOT, OUT)} (${wrong.length} wrong-page links, ${realBroken.length} broken URLs, ${altRows.size} images without alt).`);
